import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const schemaPath = path.join(root, "shared", "system_log_events.json");
const outPath = path.join(root, "src", "types", "systemLogEvents.ts");

if (!fs.existsSync(schemaPath)) {
  throw new Error(`Missing system log schema at ${schemaPath}`);
}

const schema = JSON.parse(fs.readFileSync(schemaPath, "utf8"));
const events = Array.isArray(schema.events) ? schema.events : [];

const lines = [];
lines.push("// Generated by scripts/generate-system-log-types.js");
lines.push("// Do not edit manually.");
lines.push("");
lines.push("export const SYSTEM_LOG_EVENTS = [");
for (const event of events) {
  lines.push(`  "${event}",`);
}
lines.push("] as const;");
lines.push("");
lines.push("export type SystemLogEventName = typeof SYSTEM_LOG_EVENTS[number];");
lines.push("export type SystemLogPayload = {");
lines.push("  event?: SystemLogEventName;");
lines.push("  [key: string]: any;");
lines.push("};");
lines.push("");

fs.writeFileSync(outPath, `${lines.join("\n")}\n`, "utf8");
